export function t(lang: Lang, path: string): string {
  const keys = path.split(".");
  let val: any = dict[lang];
  for (const k of keys) {
    val = val?.[k];
  }
  return typeof val === "string" ? val : path;
}

export function ta(lang: Lang, path: string): string[] {
  const keys = path.split(".");
  let val: any = dict[lang];
  for (const k of keys) {
    val = val?.[k];
  }
  return Array.isArray(val) ? val : [];
}
